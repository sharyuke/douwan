/** 把一行字符网格合并成连续的 rect（x, width），减少 DOM 节点。 */
export function pixelRuns(row) {
  const runs = []
  let start = -1
  for (let i = 0; i <= row.length; i++) {
    const on = row[i] === '1'
    if (on && start < 0) start = i
    if (!on && start >= 0) {
      runs.push({ x: start, w: i - start })
      start = -1
    }
  }
  return runs
}
